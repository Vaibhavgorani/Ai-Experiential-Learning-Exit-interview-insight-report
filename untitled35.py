def normalize_and_split(reasons_str):
    if not isinstance(reasons_str, str) or reasons_str.strip() == "":
        return set()
    # Split by semicolon or comma
    parts = [p.strip() for p in reasons_str.replace(';', ',').split(',')]
    # Map items to standard names
    mapped = []
    for p in parts:
        mapped.append(category_mapping.get(p, p))
    return set(mapped)

