# Define metric helper functions
def compute_jaccard(row):
    g = row['gold_set']
    p = row['pred_set']
    if not g and not p:
        return 1.0
    return len(g.intersection(p)) / len(g.union(p))

def compute_exact_match(row):
    return int(row['gold_set'] == row['pred_set'])

def compute_partial_match(row):
    g = row['gold_set']
    p = row['pred_set']
    if not g:
         return 1.0 if not p else 0.0
    return len(g.intersection(p)) / len(g)

