def extract_reasons_fixed(note):
    if not isinstance(note, str):
        return 'Unknown'
    note_lower = note.lower()
    reasons = []

    # Better pay elsewhere
    if any(k in note_lower for k in ['pay', 'salary', 'compensation', 'offer']):
        reasons.append('Better pay elsewhere')

    # Career growth
    # Rule: Match growth/promotion but exclude when it's explicitly about the manager not supporting growth
    has_career_keyword = any(k in note_lower for k in ['growth', 'career', 'promotion', 'advance', 'same role', 'promotion path'])
    has_manager_growth_complaint = "manager did not support my growth" in note_lower
    if has_career_keyword and not has_manager_growth_complaint:
        reasons.append('Career growth')

    # Manager relationship
    if any(k in note_lower for k in ['manager', 'leadership', 'supervisor', 'management', 'credit for my work']):
        reasons.append('Manager relationship')

    # Work-life balance
    if any(k in note_lower for k in ['balance', 'overtime', 'weekend', 'burnout', 'late nights', 'stress']):
        reasons.append('Work-life balance')

    # Higher studies
    # Use regular expressions for 'mba' to avoid matching 'Coimbatore', and exclude training programmes safely
    has_studies_keyword = (
        any(k in note_lower for k in ['master', 'study', 'studies', 'education', 'degree', 'college', 'university']) or
        re.search(r'\bmba\b', note_lower)
    )
    if has_studies_keyword and 'training' not in note_lower:
        reasons.append('Higher studies')

    # Culture
    if any(k in note_lower for k in ['culture', 'toxic', 'environment', 'ideas', 'top-down', 'welcomed']):
        reasons.append('Culture')

    # Relocation
    if any(k in note_lower for k in ['moving to', 'relocat', 'transfer', 'shifted']):
        reasons.append('Relocation')

    return '; '.join(reasons) if reasons else 'Other'

